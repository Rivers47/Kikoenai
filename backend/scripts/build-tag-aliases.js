// One-off: build backend/scraper/tag-aliases.json by joining each old-DB genre
// id against DLsite's CURRENT name for that genre.
//
// The current name is read from the per-genre search page title:
//   https://www.dlsite.com/maniax/fsr/=/genre/<NNN>/
//   <title>「<current ja name>」の作品一覧 | DLsite ...
// This works for ALL genres — including "shadow tags" DLsite removed from the
// public genre-list page (レイプ, 調教, 奴隷, …) but still applies to works. The
// genre-list page cannot see shadow tags; the per-genre search page can.
//
// REQUIRES YOUR PROXY (these pages are region-blocked). Run this script in an
// environment where the scraper's configured proxy (config.js / HTTPS_PROXY)
// is reachable:
//
//   cd backend && node scripts/build-tag-aliases.js
//
// It fetches ~300 pages sequentially (one per old-DB genre) with a small delay
// to stay polite. Output: scraper/tag-aliases.json — only entries where the
// current name differs from the old name (the renames). Unchanged genres need
// no entry (canonicalizeTagName passes them through unchanged).

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const axios = require('../scraper/axios'); // proxy-aware, with retry

const OLD_DB = path.join(__dirname, '..', 'database', 'old_tag_id.sqlite3');
const SEARCH_URL = (id) => `https://www.dlsite.com/maniax/fsr/=/genre/${String(id).padStart(3, '0')}/`;

function getOldIdToName() {
  const rows = execSync(`sqlite3 "${OLD_DB}" "SELECT id, name FROM t_tag;"`, { encoding: 'utf8' });
  const map = new Map();
  for (const line of rows.trim().split('\n')) {
    if (!line) continue;
    const [id, ...nameParts] = line.split('|');
    map.set(parseInt(id, 10), nameParts.join('|').trim());
  }
  return map;
}

// Extract the current genre name from the search page title: 「<name>」の作品一覧
function extractGenreName(html) {
  const m = html.match(/「([^」]+)」の作品一覧/);
  return m ? m[1] : null;
}

async function fetchCurrentName(id, retryLeft = 3) {
  try {
    const resp = await axios.retryGet(SEARCH_URL(id), { retry: {} });
    const name = extractGenreName(resp.data);
    return name;
  } catch (err) {
    if (retryLeft > 0) {
      await new Promise(r => setTimeout(r, 1000));
      return fetchCurrentName(id, retryLeft - 1);
    }
    return null; // genre dead / page gone → no rename
  }
}

(async () => {
  const oldMap = getOldIdToName();
  console.log(`Old DB: ${oldMap.size} genres. Fetching current names from DLsite (needs proxy)...`);

  const aliases = {};
  let renamed = 0, same = 0, dead = 0;
  const ids = [...oldMap.keys()].sort((a, b) => a - b);

  for (let i = 0; i < ids.length; i++) {
    const id = ids[i];
    const oldName = oldMap.get(id);
    const curName = await fetchCurrentName(id);
    if (curName === null) {
      dead++;
      console.log(`  [${i + 1}/${ids.length}] id=${id}  DEAD (no search page)  old="${oldName}"`);
    } else if (curName !== oldName) {
      aliases[curName] = oldName;
      renamed++;
      console.log(`  [${i + 1}/${ids.length}] id=${id}  RENAME  "${oldName}" → "${curName}"`);
    } else {
      same++;
      if (process.env.VERBOSE) console.log(`  [${i + 1}/${ids.length}] id=${id}  same  "${oldName}"`);
    }
    await new Promise(r => setTimeout(r, 250)); // be polite
  }

  console.log(`\n  same=${same}  renamed=${renamed}  dead=${dead}  total=${ids.length}`);

  const out = {
    _comment: 'DLsite genre rename map. "new_ja_name": "canonical_old_ja_name". Auto-generated by scripts/build-tag-aliases.js from old_tag_id.sqlite3 + per-genre search page titles (maniax/fsr/=/genre/NNN/). Edit and restart server to apply.',
    ...aliases,
  };
  const outPath = path.join(__dirname, '..', 'scraper', 'tag-aliases.json');
  fs.writeFileSync(outPath, JSON.stringify(out, null, 2) + '\n');
  console.log(`\nWrote ${renamed} aliases to ${outPath}`);
})().catch(err => {
  console.error('Failed:', err.message);
  process.exit(1);
});
